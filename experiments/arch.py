#!/usr/bin/env python3
"""
arch.py - Week 6 architecture ablations (schedule items #13, #14, #15, #16, #17).

Everything here is an **ablation row**, not a candidate for deployment. Weeks 1-5
established that on this problem the data is the lever and the recipe is not
(Week 4: object mAP stayed flat at 0.49 while violation recall moved +11 points).
Week 6 asks the same question of the architecture: is there headroom the recipe
sweep could not reach?

Variants are built by rewriting `yolo11.yaml` rather than by depending on any
third-party fork, so every row is reproducible from the shipped ultralytics.

  p2        item #13 - extra P2/4 detection head for small, distant workers
  cbam      item #14 - CBAM after each neck output
  se        item #14 - squeeze-excite (channel attention only)
  eca       item #14 - efficient channel attention, parameter-free per channel
  coordatt  item #14 - coordinate attention (position-aware channel attention)

Channel widths are written into the yaml explicitly because ultralytics'
`parse_model` only width-scales modules in its own `base_modules` set; an
attention block outside that set receives its args verbatim.
"""
from __future__ import annotations

import json
from pathlib import Path

import torch
import torch.nn as nn

# ---------------------------------------------------------------- attention --

class ECA(nn.Module):
    """Efficient Channel Attention (Wang et al. 2020) - a single 1-D conv across
    channels, no dimensionality reduction, ~k parameters total."""

    def __init__(self, c1: int, k: int = 3):
        super().__init__()
        self.pool = nn.AdaptiveAvgPool2d(1)
        self.conv = nn.Conv1d(1, 1, kernel_size=k, padding=k // 2, bias=False)
        self.act = nn.Sigmoid()

    def forward(self, x):
        y = self.pool(x).squeeze(-1).transpose(-1, -2)   # B,1,C
        y = self.conv(y).transpose(-1, -2).unsqueeze(-1)  # B,C,1,1
        return x * self.act(y)


class CoordAtt(nn.Module):
    """Coordinate Attention (Hou et al. 2021) - factorises channel attention into
    two 1-D position-aware maps, so it keeps where a feature is, not just how
    strong it is. Relevant here: helmet evidence is positionally constrained to
    the top of a person box."""

    def __init__(self, c1: int, reduction: int = 32):
        super().__init__()
        mid = max(8, c1 // reduction)
        self.pool_h = nn.AdaptiveAvgPool2d((None, 1))
        self.pool_w = nn.AdaptiveAvgPool2d((1, None))
        self.conv1 = nn.Conv2d(c1, mid, 1, bias=False)
        self.bn1 = nn.BatchNorm2d(mid)
        self.act = nn.SiLU()
        self.conv_h = nn.Conv2d(mid, c1, 1, bias=False)
        self.conv_w = nn.Conv2d(mid, c1, 1, bias=False)

    def forward(self, x):
        n, c, h, w = x.shape
        xh = self.pool_h(x)                      # B,C,H,1
        xw = self.pool_w(x).permute(0, 1, 3, 2)  # B,C,W,1
        y = self.act(self.bn1(self.conv1(torch.cat([xh, xw], dim=2))))
        yh, yw = torch.split(y, [h, w], dim=2)
        yw = yw.permute(0, 1, 3, 2)
        return x * self.conv_h(yh).sigmoid() * self.conv_w(yw).sigmoid()


class SE(nn.Module):
    """Squeeze-and-Excitation (Hu et al. 2018), channel attention only."""

    def __init__(self, c1: int, reduction: int = 16):
        super().__init__()
        mid = max(8, c1 // reduction)
        self.pool = nn.AdaptiveAvgPool2d(1)
        self.fc = nn.Sequential(nn.Conv2d(c1, mid, 1, bias=False), nn.SiLU(),
                                nn.Conv2d(mid, c1, 1, bias=False), nn.Sigmoid())

    def forward(self, x):
        return x * self.fc(self.pool(x))


def register_modules() -> None:
    """Expose the custom blocks to ultralytics' yaml parser (`globals()[m]`)."""
    import ultralytics.nn.tasks as tasks
    from ultralytics.nn.modules import CBAM  # defined but not re-exported into tasks
    for cls in (ECA, CoordAtt, SE, CBAM):
        setattr(tasks, cls.__name__, cls)


# ------------------------------------------------------------ yaml builders --

# Neck output channels after width scaling, per scale: (P3, P4, P5)
NECK_CH = {
    "n": (64, 128, 256),
    "s": (128, 256, 512),
    "m": (256, 512, 512),
    "l": (256, 512, 512),
    "x": (384, 768, 768),
}

_BACKBONE = """backbone:
  - [-1, 1, Conv, [64, 3, 2]]
  - [-1, 1, Conv, [128, 3, 2]]
  - [-1, 2, C3k2, [256, False, 0.25]]
  - [-1, 1, Conv, [256, 3, 2]]
  - [-1, 2, C3k2, [512, False, 0.25]]
  - [-1, 1, Conv, [512, 3, 2]]
  - [-1, 2, C3k2, [512, True]]
  - [-1, 1, Conv, [1024, 3, 2]]
  - [-1, 2, C3k2, [1024, True]]
  - [-1, 1, SPPF, [1024, 5]]
  - [-1, 2, C2PSA, [1024]]
"""

_HEADER = """# generated by experiments/arch.py - do not edit by hand
nc: {nc}
scales:
  n: [0.50, 0.25, 1024]
  s: [0.50, 0.50, 1024]
  m: [0.50, 1.00, 512]
  l: [1.00, 1.00, 512]
  x: [1.00, 1.50, 512]

"""


def _attention_yaml(module: str, scale: str, nc: int, extra: str = "") -> str:
    """Standard yolo11 neck with `module` applied to each of P3/P4/P5."""
    p3, p4, p5 = NECK_CH[scale]
    a = f", {extra}" if extra else ""
    return _HEADER.format(nc=nc) + _BACKBONE + f"""
head:
  - [-1, 1, nn.Upsample, [None, 2, "nearest"]]
  - [[-1, 6], 1, Concat, [1]]
  - [-1, 2, C3k2, [512, False]]            # 13

  - [-1, 1, nn.Upsample, [None, 2, "nearest"]]
  - [[-1, 4], 1, Concat, [1]]
  - [-1, 2, C3k2, [256, False]]            # 16
  - [-1, 1, {module}, [{p3}{a}]]           # 17 P3/8

  - [-1, 1, Conv, [256, 3, 2]]
  - [[-1, 13], 1, Concat, [1]]
  - [-1, 2, C3k2, [512, False]]            # 20
  - [-1, 1, {module}, [{p4}{a}]]           # 21 P4/16

  - [-1, 1, Conv, [512, 3, 2]]
  - [[-1, 10], 1, Concat, [1]]
  - [-1, 2, C3k2, [1024, True]]            # 24
  - [-1, 1, {module}, [{p5}{a}]]           # 25 P5/32

  - [[17, 21, 25], 1, Detect, [nc]]
"""


def _p2_yaml(nc: int) -> str:
    """Adds a P2/4 output. Pictor test persons sit at 1.6% median box area; at
    imgsz 640 that is ~25 px, below one P3/8 stride cell of context."""
    return _HEADER.format(nc=nc) + _BACKBONE + """
head:
  - [-1, 1, nn.Upsample, [None, 2, "nearest"]]
  - [[-1, 6], 1, Concat, [1]]
  - [-1, 2, C3k2, [512, False]]            # 13

  - [-1, 1, nn.Upsample, [None, 2, "nearest"]]
  - [[-1, 4], 1, Concat, [1]]
  - [-1, 2, C3k2, [256, False]]            # 16 P3/8

  - [-1, 1, nn.Upsample, [None, 2, "nearest"]]
  - [[-1, 2], 1, Concat, [1]]
  - [-1, 2, C3k2, [128, False]]            # 19 P2/4

  - [-1, 1, Conv, [128, 3, 2]]
  - [[-1, 16], 1, Concat, [1]]
  - [-1, 2, C3k2, [256, False]]            # 22 P3/8

  - [-1, 1, Conv, [256, 3, 2]]
  - [[-1, 13], 1, Concat, [1]]
  - [-1, 2, C3k2, [512, False]]            # 25 P4/16

  - [-1, 1, Conv, [512, 3, 2]]
  - [[-1, 10], 1, Concat, [1]]
  - [-1, 2, C3k2, [1024, True]]            # 28 P5/32

  - [[19, 22, 25, 28], 1, Detect, [nc]]
"""


def _plain_yaml(nc: int) -> str:
    """Stock yolo11 neck. The control arm: built and trained through exactly the
    same code path as the variants, so any difference is the variant."""
    return _HEADER.format(nc=nc) + _BACKBONE + """
head:
  - [-1, 1, nn.Upsample, [None, 2, "nearest"]]
  - [[-1, 6], 1, Concat, [1]]
  - [-1, 2, C3k2, [512, False]]            # 13

  - [-1, 1, nn.Upsample, [None, 2, "nearest"]]
  - [[-1, 4], 1, Concat, [1]]
  - [-1, 2, C3k2, [256, False]]            # 16

  - [-1, 1, Conv, [256, 3, 2]]
  - [[-1, 13], 1, Concat, [1]]
  - [-1, 2, C3k2, [512, False]]            # 19

  - [-1, 1, Conv, [512, 3, 2]]
  - [[-1, 10], 1, Concat, [1]]
  - [-1, 2, C3k2, [1024, True]]            # 22

  - [[16, 19, 22], 1, Detect, [nc]]
"""


VARIANTS = {
    "none": lambda scale, nc: _plain_yaml(nc),
    "p2": lambda scale, nc: _p2_yaml(nc),
    "cbam": lambda scale, nc: _attention_yaml("CBAM", scale, nc, "7"),
    "se": lambda scale, nc: _attention_yaml("SE", scale, nc, "16"),
    "eca": lambda scale, nc: _attention_yaml("ECA", scale, nc, "3"),
    "coordatt": lambda scale, nc: _attention_yaml("CoordAtt", scale, nc, "32"),
}


def build_yaml(variant: str, scale: str, nc: int, out_dir: Path) -> Path:
    if variant not in VARIANTS:
        raise ValueError(f"unknown variant {variant!r}; have {sorted(VARIANTS)}")
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / f"yolo11{scale}-{variant}.yaml"
    p.write_text(VARIANTS[variant](scale, nc), encoding="utf-8")
    return p


def model_stats(model) -> dict:
    """Params / GFLOPs, as ultralytics reports them."""
    from ultralytics.utils.torch_utils import get_flops, get_num_params
    m = model.model
    try:
        flops = round(float(get_flops(m, 640)), 2)
    except Exception:  # noqa: BLE001
        flops = None
    return {"params_M": round(get_num_params(m) / 1e6, 3), "GFLOPs": flops}


if __name__ == "__main__":  # smoke test: build every variant
    from ultralytics import YOLO
    register_modules()
    out = Path(__file__).resolve().parent / "cfg"
    for v in VARIANTS:
        p = build_yaml(v, "s", 4, out)
        m = YOLO(str(p))
        print(f"{v:9s} {json.dumps(model_stats(m))}")
